"""Generate src/GAMEDATA.PAS: every game typed constant and variable of the data segment, in address order.

Item boundaries come from names.tsv (IDA names of the coab listing) plus data/types.tsv overrides
(DSOFF NAME TYPE ['VALUE']) as the decompilation learns real types. Initialised data: DS[2, CONST_END);
variables: DS[VAR_START, VAR_END).
"""
import re, os, sys

CONST_START, CONST_END = 0x0002, 0x7D8C
VAR_START, VAR_END = 0x7DDE, 0xFB76
o = open('orig/GAME.bin', 'rb').read()
ds = o[0x9E70:]

def good(n):
    return not re.match(r'^(byte|word|dword|stru|unk|asc|off|seg|flt)_[0-9A-F]+$', n)

names = {}
for l in open('names.tsv'):
    k, off, kind, n = l.rstrip('\n').split('\t')
    if k == 'DS': names[int(off, 16)] = n
cuts = set()
if os.path.exists('data/cuts.txt'):
    cuts = {int(x, 16) for x in open('data/cuts.txt').read().split()}
over = {}
if os.path.exists('data/types.tsv'):
    for l in open('data/types.tsv'):
        if l.strip() and not l.startswith('#'):
            p = l.rstrip('\n').split('\t')
            over[int(p[0], 16)] = p[1:]

def items(lo, hi):
    """[(start, size, name, type or None)]"""
    cuts_ = sorted({a for a in list(names) + list(over) + list(cuts) if lo <= a < hi} | {lo})
    # an override with an explicit size swallows the name cuts inside it
    for o, v in over.items():
        if len(v) > 3:
            cuts_ = [a for a in cuts_ if not o < a < o + int(v[3])]
    out = []
    used = set()
    for i, a in enumerate(cuts_):
        b = cuts_[i+1] if i + 1 < len(cuts_) else hi
        if a in over:
            n, t = over[a][0], over[a][1]
        else:
            n = names.get(a)
            n = n if n and good(n) else None
            n = (n + '_%04X' % a) if n else 'd%04X' % a
            t = None
        if n.lower() in used: n += '_%04X' % a
        used.add(n.lower())
        out.append((a, b - a, n, t))
    return out

def ptype(size):
    return {1: 'byte', 2: 'word', 4: 'longint'}.get(size, 'array[0..%d] of byte' % (size - 1))

def pval(a, size):
    b = ds[a:a+size]
    if size == 1: return str(b[0])
    if size == 2: return str(b[0] | b[1] << 8)
    if size == 4: return str(int.from_bytes(b, 'little', signed=True))
    return None

import json
shared = set()
for v in json.load(open('out/procs.json')).values():
    for pp in v['procs']:
        for c in pp.get('copies', []):
            shared.add(('S%d' % c['n'], 'string[%d]' % c['n']) if c['rtl'] == 0xA89 and c['n'] != 255 else
                       (('B%d' % c['n'], 'array[0..%d] of byte' % (c['n'] - 1)) if c['rtl'] != 0xA89 else None))
shared.discard(None)
if os.path.exists('data/strfunc_types.json'):
    for n in json.load(open('data/strfunc_types.json')).values():
        shared.add(('S%d' % n, 'string[%d]' % n))
L = ['{ GAMEDATA: all game typed constants and variables (generated by tools/gendata.py) }',
     '{$A-,B-,D-,E-,F+,G-,I-,L-,N-,O-,R-,S-,V-,X-}',
     'unit GAMEDATA;', '', 'interface', '', 'type']
L += ['  %s = %s;' % t for t in sorted(shared)]
L += ['', 'const']
for a, size, n, t in items(CONST_START, CONST_END):
    if t:
        L.append('{%04X} %s: %s = %s;' % (a, n, t, over[a][2] if len(over[a]) > 2 else '?'))
        continue
    v = pval(a, size)
    if v is not None:
        L.append('{%04X} %s: %s = %s;' % (a, n, ptype(size), v))
    else:
        vals = [str(x) for x in ds[a:a+size]]
        head = '{%04X} %s: %s = (' % (a, n, ptype(size))
        line = head; first = True
        for x in vals:
            add = x if first else ',' + x
            if len(line) + len(add) > 118:
                L.append(line + ','); line = '    ' + x
            else:
                line += add
            first = False
        L.append(line + ');')
L += ['', 'var']
for a, size, n, t in items(VAR_START, VAR_END):
    L.append('{%04X} %s: %s;' % (a, n, t or ptype(size)))
L += ['', 'implementation', '', 'end.']
open('src/GAMEDATA.PAS', 'w', newline='\r\n').write('\n'.join(L) + '\n')
print('consts', len(items(CONST_START, CONST_END)), 'vars', len(items(VAR_START, VAR_END)))
